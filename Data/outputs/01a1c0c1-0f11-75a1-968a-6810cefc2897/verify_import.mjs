import { FileBlob, SpreadsheetFile } from "@oai/artifact-tool";
const file="D:/Tool/Server_Leo_Nguyen/Data/outputs/01a1c0c1-0f11-75a1-968a-6810cefc2897/Ke_hoach_san_xuat_Daily_Task.xlsx";
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(file));
const plan=wb.worksheets.getItem("Kế hoạch");
const tasks=wb.worksheets.getItem("Daily Task");
const summary=wb.worksheets.getItem("Tổng quan");
const bom=wb.worksheets.getItem("BOM Assembly");
const choice=bom.getRange("O5").values[0][0];
plan.getRange("B5:C5").values=[["A290",choice]];
plan.getRange("G5:H5").values=[[new Date(Date.UTC(2026,10,9)),new Date(Date.UTC(2026,10,11))]];
plan.getRange("I5").values=[["S1 Vinh"]];
plan.getRange("J5").values=[[null]];
wb.recalculate();
const planValues=plan.getRange("A5:M5").values[0];
const taskValues=tasks.getRange("A5:J8").values;
const validation={project:plan.getRange("B5").dataValidation,assembly:plan.getRange("C5").dataValidation,team:plan.getRange("I5").dataValidation};
const names=(await wb.inspect({kind:"definedName",maxChars:3000})).ndjson;
const taskPlan=tasks.getRange("G5").values[0][0];
tasks.getRange("H5").values=[[taskPlan]];
wb.recalculate();
const completed={status:tasks.getRange("J5").values[0][0],progress:tasks.getRange("I5").values[0][0],dashboard:summary.getRange("A4:K5").values};
const errors=(await wb.inspect({kind:"match",searchTerm:"#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!",options:{useRegex:true,maxResults:100},summary:"sample workflow formula scan"})).ndjson;
console.log(JSON.stringify({choice,planValues,taskValues,validation,names,completed,errors},null,2));
